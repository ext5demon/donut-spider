#!/usr/bin/env python3
"""Embed the checked-in dev7.1 picker assets in the runner header. Requires Pillow."""
from pathlib import Path
import json,wave,struct
from PIL import Image

root=Path(__file__).resolve().parents[1];assets=root/'assets/picker'
layout=json.loads((assets/'layout.json').read_text())
im=Image.open(assets/'atlas.png').convert('RGBA')
palette=[(255,255,255,0),(255,255,255,255),(0,0,0,255),(255,0,0,255)]
indices=[]
for p in (im.get_flattened_data() if hasattr(im,'get_flattened_data') else im.getdata()):
 if p[3]==0:p=palette[0]
 assert p in palette,p
 indices.append(palette.index(p))
packed=[sum(indices[i+j]<<(6-2*j) for j in range(4)) for i in range(0,len(indices),4)]
lines=['/* Generated by tools/embed_picker_assets.py. See assets/picker/NOTICE.txt. */',
       '#ifndef PICKER_ASSETS_H','#define PICKER_ASSETS_H','#include <stdint.h>',
       'typedef struct { uint16_t x,y,w,h; int16_t advance,offset; } PickerGlyph;',
       'typedef struct { uint16_t x,y,w,h; } PickerSprite;',
       '#define PICKER_ATLAS_W 256','#define PICKER_ATLAS_H 128',
       'static const uint8_t pickerAtlasPacked[] = {']
for i in range(0,len(packed),32):lines.append('    '+','.join(str(v) for v in packed[i:i+32])+',')
lines+=['};']
for f in layout['fonts']:
 lines.append('static const PickerGlyph picker_'+f['name']+'[95] = {')
 assert [g[0] for g in f['glyphs']]==list(range(32,127))
 for code,*g in f['glyphs']:lines.append('    {'+','.join(map(str,g))+'},')
 lines.append('};')
for name in ['icons','heart']:
 lines.append('static const PickerSprite picker_'+name+'[] = {')
 for g in layout[name]:lines.append('    {'+','.join(map(str,g))+'},')
 lines.append('};')
for name in ['move','select','chapter1','chapter2','chapter3','chapter4','chapter5']:
 with wave.open(str(assets/(name+'.wav')),'rb') as f:
  assert f.getnchannels()==1 and f.getsampwidth()==2
  rate=f.getframerate();raw=f.readframes(f.getnframes());samples=struct.unpack('<'+'h'*(len(raw)//2),raw)
 lines += [f'#define PICKER_{name.upper()}_RATE {rate}',f'#define PICKER_{name.upper()}_FRAMES {len(samples)}',
           '#ifdef PICKER_UI_SOUND',f'static const int16_t pickerSound_{name}[] = {{']
 for i in range(0,len(samples),24):lines.append('    '+','.join(map(str,samples[i:i+24]))+',')
 lines+=['};','#endif']
lines+=['#endif','']
target=root/'src/ps3/picker_assets.h';target.write_text('\n'.join(lines),encoding='utf-8',newline='\n')
print(target,len(packed),'packed atlas bytes')
